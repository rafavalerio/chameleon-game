/**
 * Get a topic by its ID
 */
export function getTopicById(id: string): Topic | undefined {
  return topics.find((topic) => topic.id === id);
}

/**
 * Get a random word from a topic
 */
export function getRandomWord(topic: Topic): string {
  return topic.words[Math.floor(Math.random() * topic.words.length)];
}

/**
 * Get random questions from a topic (shuffled)
 */
export function getRandomQuestions(topic: Topic, count: number): string[] {
  const shuffled = [...topic.questions].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length));
}

/**
 * Get all words from a topic (useful for chameleon guessing)
 */
export function getTopicWords(topic: Topic): string[] {
  return [...topic.words];
}
